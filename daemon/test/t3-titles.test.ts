import assert from 'node:assert/strict';
import {test} from 'node:test';
import {mkdtemp,mkdir,rm,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import {t3Title} from '../src/t3-titles.js';
import {LiveCaptions,sessionMetadata} from '../src/live-captions.js';

test('T3 exact bindings follow renames and preserve standalone/provider fallbacks', async t=>{
 const home=await mkdtemp(join(tmpdir(),'t3-titles-'));
 t.after(()=>rm(home,{recursive:true,force:true}));
 assert.equal(t3Title(home,'claude','session'),'');
 await mkdir(join(home,'.t3','userdata'),{recursive:true});
 await mkdir(join(home,'.codex'),{recursive:true});
 await writeFile(join(home,'.codex','session_index.jsonl'),JSON.stringify({id:'codex-session',thread_name:'Codex sidebar title'})+'\n');
 const path=join(home,'.t3','userdata','statev2.sqlite');
 const db=new DatabaseSync(path);t.after(()=>db.close());
 db.exec(`CREATE TABLE orchestration_v2_projection_threads(thread_id TEXT,title TEXT,deleted_at TEXT);
 CREATE TABLE orchestration_v2_projection_provider_threads(thread_id TEXT,driver TEXT,owner_node_id TEXT,payload_json TEXT);`);
 const add=(thread:string,driver:string,id:string,owner:string|null=null,strength='strong')=>db.prepare('INSERT INTO orchestration_v2_projection_provider_threads VALUES(?,?,?,?)').run(thread,driver,owner,JSON.stringify({nativeThreadRef:{nativeId:id,strength}}));
 db.prepare('INSERT INTO orchestration_v2_projection_threads VALUES(?,?,NULL)').run('t3','Old title');
 add('t3','claudeAgent','session');
 assert.equal(t3Title(home,'claude','session'),'Old title');
 db.prepare('UPDATE orchestration_v2_projection_threads SET title=?').run('Renamed title');
 assert.equal((await sessionMetadata('claude','session',{sessionTitle:'Old provider title'},home,{})).title,'Renamed title');
 assert.equal((await sessionMetadata('claude','standalone',{sessionTitle:'Claude title'},home,{})).title,'Claude title');
 assert.equal((await sessionMetadata('codex','codex-session',{},home,{})).title,'Codex sidebar title');
 const config=join(home,'captions.json');await writeFile(config,JSON.stringify({enabled:true}));
 const live=new LiveCaptions(config,home,{});
 const snapshot={version:1 as const,sessions:[{id:'claude:session',attentionUntil:0,activeUntil:100000,lastMainEventAt:1,lastSeenAt:1,hadWork:true,completionPending:false,subagents:[]}]};
 live.observe({sessionId:'claude:session',sessionTitle:'Old provider title'});
 await live.refresh(snapshot);
 const view={state:'working' as const,sessionId:'claude:session',pinned:false,index:1,count:1,notice:false,browsing:true};
 assert.equal(live.compact(view,1000,snapshot)?.title,'Renamed title');
 db.prepare('UPDATE orchestration_v2_projection_threads SET title=?').run('Renamed again');
 await live.refresh(snapshot);
 assert.equal(live.compact(view,2000,snapshot)?.title,'Renamed again');
 db.prepare('UPDATE orchestration_v2_projection_threads SET title=?').run('Renamed title');
 assert.equal(t3Title(home,'codex','session'),''); // Same ID, different provider.
 add('t3','claudeAgent','child','node-1');
 add('t3','claudeAgent','weak',null,'weak');
 assert.equal(t3Title(home,'claude','child'),'');assert.equal(t3Title(home,'claude','weak'),'');
 db.prepare('INSERT INTO orchestration_v2_projection_threads VALUES(?,?,NULL)').run('other','Other title');
 add('other','claudeAgent','session');
 assert.equal(t3Title(home,'claude','session'),'');
 assert.equal((await sessionMetadata('claude','session',{sessionTitle:'Provider fallback'},home,{})).title,'Provider fallback');
 db.exec("UPDATE orchestration_v2_projection_threads SET deleted_at='deleted' WHERE thread_id='other'");
 assert.equal(t3Title(home,'claude','session'),'Renamed title');
 db.exec('DROP TABLE orchestration_v2_projection_provider_threads');
 assert.equal(t3Title(home,'claude','session'),'');
 assert.equal((await sessionMetadata('codex','codex-session',{},home,{})).title,'Codex sidebar title');
});
